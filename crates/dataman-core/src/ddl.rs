use std::sync::Arc;

use anyhow::{Context as _, Result};

use crate::Task;
use crate::conn::{Connection, first_ok};
use crate::schema::RelKind;
use crate::sqlgen::{qualified, quote_ident, quote_literal, view_ddl};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Identity {
    Always,
    ByDefault,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Generated {
    Stored,
    Virtual,
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct ColumnDef {
    pub name: String,
    pub type_name: String,
    pub not_null: Option<bool>,
    pub default: Option<String>,
    pub identity: Option<Identity>,
    pub generated: Option<Generated>,
    pub collation: Option<String>,
    pub comment: Option<String>,
    pub serial: bool,
}

#[derive(Clone, Debug, PartialEq)]
pub struct ConstraintDef {
    pub name: String,
    pub kind: char,
    pub definition: String,
}

#[derive(Clone, Debug, PartialEq)]
pub struct TableDef {
    pub database: String,
    pub schema: String,
    pub name: String,
    pub kind: RelKind,
    pub unlogged: bool,
    pub columns: Vec<ColumnDef>,
    pub constraints: Vec<ConstraintDef>,
    pub indexes: Vec<String>,
    pub partition_by: Option<String>,
    pub comment: Option<String>,
    pub keys_reported: bool,
    pub notes: Vec<String>,
}

impl TableDef {
    pub fn new(database: &str, schema: &str, name: &str) -> TableDef {
        TableDef {
            database: database.into(),
            schema: schema.into(),
            name: name.into(),
            kind: RelKind::Table,
            unlogged: false,
            columns: vec![],
            constraints: vec![],
            indexes: vec![],
            partition_by: None,
            comment: None,
            keys_reported: true,
            notes: vec![],
        }
    }
}

fn serial_type(type_name: &str) -> Option<&'static str> {
    match type_name {
        "integer" => Some("serial"),
        "bigint" => Some("bigserial"),
        "smallint" => Some("smallserial"),
        _ => None,
    }
}

/// Always quoted: `"C"` must not fold to `c`.
fn quote_collation(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

fn column_line(c: &ColumnDef, keys: bool) -> String {
    let serial = c.serial && c.identity.is_none() && c.generated.is_none();
    let ty = match serial.then(|| serial_type(&c.type_name)).flatten() {
        Some(s) => s.to_string(),
        None => c.type_name.clone(),
    };
    let mut s = format!("{} {ty}", quote_ident(&c.name));
    if let Some(coll) = &c.collation {
        s.push_str(" COLLATE ");
        s.push_str(&quote_collation(coll));
    }
    match (c.generated, &c.default) {
        (Some(g), Some(expr)) => {
            s.push_str(&format!(" GENERATED ALWAYS AS ({expr})"));
            s.push_str(if g == Generated::Stored { " STORED" } else { " VIRTUAL" });
        }
        _ => {
            if let Some(id) = c.identity {
                s.push_str(if id == Identity::Always { " GENERATED ALWAYS AS IDENTITY" } else { " GENERATED BY DEFAULT AS IDENTITY" });
            }
        }
    }
    if keys && c.not_null == Some(true) && c.identity.is_none() && !(serial && serial_type(&c.type_name).is_some()) {
        s.push_str(" NOT NULL");
    }
    if c.generated.is_none() && c.identity.is_none() && !(serial && serial_type(&c.type_name).is_some())
        && let Some(d) = &c.default
    {
        s.push_str(" DEFAULT ");
        s.push_str(d);
    }
    s
}

pub fn render(t: &TableDef) -> String {
    let q = qualified(Some(&t.schema), &t.name);
    let mut out = String::new();
    out.push_str(&format!("-- {q}: generated from the catalog of {}\n", quote_ident(&t.database)));
    if !t.keys_reported {
        out.push_str("-- This server's catalog does not report keys, NOT NULL or defaults: only columns and types follow.\n");
    }
    for n in &t.notes {
        out.push_str(&format!("-- {n}\n"));
    }
    let kind = match t.kind {
        RelKind::Foreign => "FOREIGN TABLE",
        _ if t.unlogged => "UNLOGGED TABLE",
        _ => "TABLE",
    };
    let mut lines: Vec<String> = t.columns.iter().map(|c| column_line(c, t.keys_reported)).collect();
    if t.keys_reported {
        lines.extend(t.constraints.iter().map(|c| format!("CONSTRAINT {} {}", quote_ident(&c.name), c.definition)));
    }
    out.push_str(&format!("CREATE {kind} {q} ("));
    if lines.is_empty() {
        out.push(')');
    } else {
        out.push('\n');
        out.push_str(&lines.iter().map(|l| format!("    {l}")).collect::<Vec<_>>().join(",\n"));
        out.push_str("\n)");
    }
    if let Some(p) = &t.partition_by {
        out.push_str(&format!(" PARTITION BY {p}"));
    }
    out.push_str(";\n");
    if !t.indexes.is_empty() {
        out.push('\n');
        for i in &t.indexes {
            out.push_str(i.trim_end_matches(';'));
            out.push_str(";\n");
        }
    }
    let comments: Vec<String> = t
        .comment
        .iter()
        .map(|c| format!("COMMENT ON TABLE {q} IS {};", quote_literal(c)))
        .chain(t.columns.iter().filter_map(|c| {
            c.comment.as_ref().map(|txt| format!("COMMENT ON COLUMN {q}.{} IS {};", quote_ident(&c.name), quote_literal(txt)))
        }))
        .collect();
    if !comments.is_empty() {
        out.push('\n');
        for c in comments {
            out.push_str(&c);
            out.push('\n');
        }
    }
    out
}

fn get(r: &[Option<String>], i: usize) -> Option<String> {
    r.get(i).cloned().flatten().filter(|s| !s.is_empty())
}

fn truthy(v: Option<String>) -> Option<bool> {
    match v.as_deref() {
        Some("t" | "true" | "TRUE" | "1" | "YES" | "yes") => Some(true),
        Some("f" | "false" | "FALSE" | "0" | "NO" | "no") => Some(false),
        _ => None,
    }
}

impl Connection {
    pub fn table_ddl(self: &Arc<Self>, database: &str, schema: &str, name: &str) -> Task<String> {
        let (this, db, schema, name) = (self.clone(), database.to_string(), schema.to_string(), name.to_string());
        self.spawn(async move {
            match this.engine() {
                crate::config::Engine::MySql => this.show_create("TABLE", &db, &schema, &name).await,
                crate::config::Engine::SqlServer => this.ms_table_ddl(&db, &schema, &name).await,
                _ => Ok(render(&this.table_def(&db, &schema, &name).await?)),
            }
        })
    }

    async fn ms_table_ddl(&self, db: &str, schema: &str, name: &str) -> Result<String> {
        use crate::schema::ms;
        let client = self.meta(db).await?;
        let cols = ms::columns(&client, schema, name).await.with_context(|| format!("{schema}.{name} is not in the catalog"))?;
        if cols.is_empty() {
            anyhow::bail!("{schema}.{name} is not in the catalog");
        }
        let home = if schema.eq_ignore_ascii_case("dbo") { "dbo" } else { "" };
        let cons = first_ok(&client, &[&ms::constraints_sql(schema, name)]).await.map(|r| ms::parse_constraints(home, &r)).unwrap_or_default();
        let idx = ms::indexes(&client, schema, name).await.unwrap_or_default();
        let d = self.dialect();
        Ok(format!(
            "-- {}: generated from the catalog of {}\n{}",
            d.qualified(Some(schema), name),
            d.quote_ident(db),
            ms::table_ddl(schema, name, &cols, &cons, &idx)
        ))
    }

    async fn show_create(&self, what: &str, db: &str, schema: &str, name: &str) -> Result<String> {
        use crate::schema::my;
        let client = self.meta(db).await?;
        let rows = first_ok(&client, &[&my::show_create(what, schema, name)]).await?;
        let body = my::parse_show_create(what, &rows).with_context(|| format!("{schema}.{name} is not in the catalog"))?;
        let d = self.dialect();
        Ok(format!("-- {}: generated from the catalog of {}\n{body}\n", d.qualified(Some(schema), name), d.quote_ident(db)))
    }

    pub fn view_definition(self: &Arc<Self>, database: &str, schema: &str, name: &str) -> Task<Option<String>> {
        let (this, db, schema, name) = (self.clone(), database.to_string(), schema.to_string(), name.to_string());
        self.spawn(async move {
            if this.engine() == crate::config::Engine::MySql {
                return Ok(this.show_create("VIEW", &db, &schema, &name).await.ok());
            }
            if this.engine() == crate::config::Engine::SqlServer {
                let client = this.meta(&db).await?;
                let rows = first_ok(&client, &[&crate::schema::ms::definition_sql(&schema, &name)]).await?;
                return Ok(rows.first().and_then(|r| get(r, 0)).map(|d| format!("{};", d.trim().trim_end_matches(';'))));
            }
            let client = this.meta(&db).await?;
            let sql = format!(
                "SELECT pg_catalog.pg_get_viewdef(c.oid, true), c.relkind FROM pg_catalog.pg_class c \
                 JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = {} AND c.relname = {}",
                quote_literal(&schema),
                quote_literal(&name)
            );
            let rows = first_ok(&client, &[&sql]).await?;
            let Some(r) = rows.first() else { return Ok(None) };
            let materialized = get(r, 1).as_deref() == Some("m");
            Ok(get(r, 0).filter(|d| !d.trim().is_empty()).map(|d| view_ddl(&schema, &name, materialized, &d)))
        })
    }

    pub async fn table_def(&self, db: &str, schema: &str, name: &str) -> Result<TableDef> {
        let client = self.meta(db).await?;
        let mut t = TableDef::new(db, schema, name);
        t.keys_reported = !self.info.is_lar;
        let where_rel = format!(
            "FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
             WHERE n.nspname = {} AND c.relname = {}",
            quote_literal(schema),
            quote_literal(name)
        );
        let full = format!(
            "SELECT c.oid, c.relkind, c.relpersistence, c.relispartition, pg_catalog.pg_get_partkeydef(c.oid), \
             pg_catalog.obj_description(c.oid, 'pg_class') {where_rel}"
        );
        let short = format!("SELECT c.oid, c.relkind {where_rel}");
        let rel = first_ok(&client, &[&full, &short]).await?.into_iter().next().with_context(|| format!("{schema}.{name} is not in the catalog"))?;
        let oid: u32 = get(&rel, 0).and_then(|o| o.parse().ok()).context("the catalog gave no oid")?;
        t.kind = get(&rel, 1).and_then(|k| RelKind::from_relkind(&k)).unwrap_or(RelKind::Table);
        t.unlogged = get(&rel, 2).as_deref() == Some("u");
        let is_partition = truthy(get(&rel, 3)) == Some(true);
        if t.keys_reported {
            t.partition_by = get(&rel, 4).filter(|_| t.kind == RelKind::Partitioned);
            t.comment = get(&rel, 5);
        }

        // Columns: the full query (PostgreSQL 12+), then without generated columns (10+), then the
        // bare catalog (LAR), then information_schema.
        let cols_from = format!(
            "FROM pg_catalog.pg_attribute a \
             JOIN pg_catalog.pg_type ty ON ty.oid = a.atttypid \
             LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
             LEFT JOIN pg_catalog.pg_collation co ON co.oid = a.attcollation \
             WHERE a.attrelid = {oid} AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum"
        );
        let common = "a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod), a.attnotnull, \
             pg_catalog.pg_get_expr(d.adbin, d.adrelid), a.attidentity";
        let rest = format!(
            "CASE WHEN a.attcollation <> 0 AND a.attcollation <> ty.typcollation THEN co.collname END, \
             pg_catalog.col_description(a.attrelid, a.attnum), \
             pg_catalog.pg_get_serial_sequence({}, a.attname) {cols_from}",
            quote_literal(&qualified(Some(schema), name))
        );
        let q12 = format!("SELECT {common}, a.attgenerated, {rest}");
        let q10 = format!("SELECT {common}, '' AS attgenerated, {rest}");
        let bare = format!(
            "SELECT a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attnum \
             FROM pg_catalog.pg_attribute a WHERE a.attrelid = {oid} AND a.attnum > 0 ORDER BY a.attnum"
        );
        let queries: Vec<&str> = if t.keys_reported { vec![&q12, &q10, &bare] } else { vec![&bare] };
        match first_ok(&client, &queries).await {
            Ok(rows) if rows.first().is_some_and(|r| r.len() >= 9) => {
                for r in rows {
                    let Some(name) = get(&r, 0) else { continue };
                    let default = get(&r, 3);
                    let seq = get(&r, 8);
                    let identity = match get(&r, 4).as_deref() {
                        Some("a") => Some(Identity::Always),
                        Some("d") => Some(Identity::ByDefault),
                        _ => None,
                    };
                    let generated = match get(&r, 5).as_deref() {
                        Some("s") => Some(Generated::Stored),
                        Some("v") => Some(Generated::Virtual),
                        _ => None,
                    };
                    let serial = identity.is_none() && generated.is_none() && seq.is_some() && default.as_deref().is_some_and(|d| d.starts_with("nextval("));
                    t.columns.push(ColumnDef {
                        name,
                        type_name: get(&r, 1).unwrap_or_default(),
                        not_null: truthy(get(&r, 2)),
                        default,
                        identity,
                        generated,
                        collation: get(&r, 6),
                        comment: get(&r, 7),
                        serial,
                    });
                }
            }
            Ok(rows) if !rows.is_empty() => {
                for r in rows {
                    let Some(name) = get(&r, 0) else { continue };
                    let not_null = if t.keys_reported { truthy(get(&r, 2)) } else { None };
                    t.columns.push(ColumnDef { name, type_name: get(&r, 1).unwrap_or_default(), not_null, ..Default::default() });
                }
            }
            _ => {
                let is = format!(
                    "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns \
                     WHERE table_schema = {} AND table_name = {} ORDER BY ordinal_position",
                    quote_literal(schema),
                    quote_literal(name)
                );
                for r in first_ok(&client, &[&is]).await.context("columns unavailable")? {
                    let Some(name) = get(&r, 0) else { continue };
                    let not_null = if t.keys_reported { truthy(get(&r, 2)).map(|n| !n) } else { None };
                    let default = if t.keys_reported { get(&r, 3) } else { None };
                    t.columns.push(ColumnDef { name, type_name: get(&r, 1).unwrap_or_default(), not_null, default, ..Default::default() });
                }
            }
        }
        if !t.keys_reported {
            return Ok(t);
        }

        // NOT NULL constraints of PostgreSQL 18 are already on the columns.
        let cons = format!(
            "SELECT conname, contype, pg_catalog.pg_get_constraintdef(oid, true) FROM pg_catalog.pg_constraint \
             WHERE conrelid = {oid} AND contype IN ('p','u','c','x','f') \
             ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END, conname"
        );
        match first_ok(&client, &[&cons]).await {
            Ok(rows) => {
                for r in rows {
                    let (Some(name), Some(kind), Some(definition)) = (get(&r, 0), get(&r, 1), get(&r, 2)) else { continue };
                    t.constraints.push(ConstraintDef { name, kind: kind.chars().next().unwrap_or('c'), definition });
                }
            }
            Err(e) => t.notes.push(format!("constraints unavailable: {e}")),
        }
        let idx = format!(
            "SELECT pg_catalog.pg_get_indexdef(i.indexrelid) FROM pg_catalog.pg_index i \
             JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid WHERE i.indrelid = {oid} \
             AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint k WHERE k.conindid = i.indexrelid \
             AND k.conrelid = i.indrelid AND k.contype IN ('p','u','x')) ORDER BY ic.relname"
        );
        match first_ok(&client, &[&idx]).await {
            Ok(rows) => t.indexes = rows.iter().filter_map(|r| get(r, 0)).collect(),
            Err(e) => t.notes.push(format!("indexes unavailable: {e}")),
        }
        let parents = format!(
            "SELECT i.inhparent::pg_catalog.regclass::text, pg_catalog.pg_get_expr(c.relpartbound, c.oid) \
             FROM pg_catalog.pg_inherits i JOIN pg_catalog.pg_class c ON c.oid = i.inhrelid WHERE i.inhrelid = {oid} ORDER BY i.inhseqno"
        );
        if let Ok(rows) = first_ok(&client, &[&parents]).await {
            for r in rows {
                let Some(parent) = get(&r, 0) else { continue };
                match get(&r, 1).filter(|_| is_partition) {
                    Some(bound) => t.notes.push(format!("A partition of {parent} ({bound}): attach it with PARTITION OF {parent} {bound}.")),
                    None => t.notes.push(format!("Inherits from {parent}: the inherited columns are listed too; add INHERITS ({parent}) to keep the link.")),
                }
            }
        }
        if t.kind == RelKind::Foreign {
            t.notes.push("A foreign table: add SERVER and OPTIONS before running it.".into());
        }
        Ok(t)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str) -> ColumnDef {
        ColumnDef { name: name.into(), type_name: ty.into(), ..Default::default() }
    }

    #[test]
    fn renders_columns_constraints_indexes_comments() {
        let mut t = TableDef::new("dataman", "shop", "orders");
        t.columns = vec![
            ColumnDef { identity: Some(Identity::Always), not_null: Some(true), ..col("id", "bigint") },
            ColumnDef { not_null: Some(true), default: Some("'new'::text".into()), comment: Some("it's the state".into()), ..col("status", "text") },
            ColumnDef { collation: Some("C".into()), ..col("Code", "character varying(10)") },
            ColumnDef { generated: Some(Generated::Stored), default: Some("(total * 2)".into()), ..col("twice", "numeric") },
            ColumnDef { serial: true, not_null: Some(true), default: Some("nextval('shop.orders_seq_seq'::regclass)".into()), ..col("seq", "integer") },
        ];
        t.constraints = vec![
            ConstraintDef { name: "orders_pkey".into(), kind: 'p', definition: "PRIMARY KEY (id)".into() },
            ConstraintDef { name: "orders_customer_fkey".into(), kind: 'f', definition: "FOREIGN KEY (customer) REFERENCES shop.customers(id)".into() },
        ];
        t.indexes = vec!["CREATE INDEX orders_status_idx ON shop.orders USING btree (status)".into()];
        t.comment = Some("orders".into());
        let sql = render(&t);
        let expected = "-- shop.orders: generated from the catalog of dataman\n\
CREATE TABLE shop.orders (\n    \
id bigint GENERATED ALWAYS AS IDENTITY,\n    \
status text NOT NULL DEFAULT 'new'::text,\n    \
\"Code\" character varying(10) COLLATE \"C\",\n    \
twice numeric GENERATED ALWAYS AS ((total * 2)) STORED,\n    \
seq serial,\n    \
CONSTRAINT orders_pkey PRIMARY KEY (id),\n    \
CONSTRAINT orders_customer_fkey FOREIGN KEY (customer) REFERENCES shop.customers(id)\n\
);\n\
\n\
CREATE INDEX orders_status_idx ON shop.orders USING btree (status);\n\
\n\
COMMENT ON TABLE shop.orders IS 'orders';\n\
COMMENT ON COLUMN shop.orders.status IS 'it''s the state';\n";
        assert_eq!(sql, expected);
    }

    #[test]
    fn serial_only_for_integer_types() {
        let c = ColumnDef { serial: true, default: Some("nextval('s'::regclass)::text".into()), ..col("x", "text") };
        assert_eq!(column_line(&c, true), "x text DEFAULT nextval('s'::regclass)::text");
        let c = ColumnDef { serial: true, default: Some("nextval('s'::regclass)".into()), ..col("x", "bigint") };
        assert_eq!(column_line(&c, true), "x bigserial");
        let c = ColumnDef { identity: Some(Identity::ByDefault), not_null: Some(true), ..col("x", "integer") };
        assert_eq!(column_line(&c, true), "x integer GENERATED BY DEFAULT AS IDENTITY");
        let c = ColumnDef { generated: Some(Generated::Virtual), default: Some("(a + 1)".into()), ..col("x", "integer") };
        assert_eq!(column_line(&c, true), "x integer GENERATED ALWAYS AS ((a + 1)) VIRTUAL");
    }

    #[test]
    fn lar_lists_columns_and_says_what_is_missing() {
        let mut t = TableDef::new("lar", "public", "demo_orders");
        t.keys_reported = false;
        t.columns = vec![ColumnDef { not_null: Some(true), ..col("id", "bigint") }, col("total", "double precision")];
        t.constraints = vec![ConstraintDef { name: "k".into(), kind: 'p', definition: "PRIMARY KEY (id)".into() }];
        let sql = render(&t);
        assert_eq!(
            sql,
            "-- public.demo_orders: generated from the catalog of lar\n\
-- This server's catalog does not report keys, NOT NULL or defaults: only columns and types follow.\n\
CREATE TABLE public.demo_orders (\n    id bigint,\n    total double precision\n);\n"
        );
    }

    #[test]
    fn partitioned_unlogged_and_empty() {
        let mut t = TableDef::new("db", "public", "events");
        t.kind = RelKind::Partitioned;
        t.partition_by = Some("RANGE (at)".into());
        t.columns = vec![col("at", "timestamp with time zone")];
        assert!(render(&t).contains("CREATE TABLE public.events (\n    at timestamp with time zone\n) PARTITION BY RANGE (at);\n"));
        let mut u = TableDef::new("db", "public", "scratch");
        u.unlogged = true;
        assert!(render(&u).contains("CREATE UNLOGGED TABLE public.scratch ();"));
    }
}
